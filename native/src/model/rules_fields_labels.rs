/// Libellé d'un champ ; une heure « HH:MM » (déclencheurs quotidiens) n'a pas le même libellé qu'une date.
pub fn field_label(name: &str, kind: &str) -> String {
    if name == "at" && kind == "text" {
        return "Heure (HH:MM)".to_string();
    }
    FIELDS.iter().find(|(key, _)| *key == name).map_or_else(|| name.to_string(), |(_, text)| text.to_string())
}

/// Libellé d'une valeur énumérée (`ge` devient « supérieur ou égal à »).
pub fn choice_label(value: &str) -> String {
    CHOICES.iter().find(|(key, _)| *key == value).map_or_else(|| value.to_string(), |(_, text)| text.to_string())
}
